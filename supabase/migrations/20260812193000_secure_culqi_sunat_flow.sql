-- Secure, idempotent payment and electronic receipt support.

alter table public.transacciones_pago
  add column if not exists idempotency_key uuid,
  add column if not exists culqi_token_hash text,
  add column if not exists datos_facturacion jsonb not null default '{}'::jsonb,
  add column if not exists culqi_card_brand text,
  add column if not exists culqi_card_last4 varchar(4),
  add column if not exists culqi_outcome_code text,
  add column if not exists culqi_request_id text,
  add column if not exists verificado_proveedor_en timestamptz;

update public.transacciones_pago
set culqi_token_id = null,
    respuesta_culqi = null
where culqi_token_id is not null
   or respuesta_culqi is not null;

comment on column public.transacciones_pago.culqi_token_id is
  'Legacy only. Culqi tokens must never be persisted.';
comment on column public.transacciones_pago.respuesta_culqi is
  'Legacy only. Full provider responses must never be persisted.';

alter table public.transacciones_pago
  drop constraint if exists transacciones_pago_estado_check;

alter table public.transacciones_pago
  add constraint transacciones_pago_estado_check
  check (estado in ('pendiente', 'procesando', 'pendiente_3ds', 'exitoso', 'fallido', 'reembolsado'));

create unique index if not exists transacciones_pago_idempotency_uidx
  on public.transacciones_pago (idempotency_key)
  where idempotency_key is not null;

create index if not exists transacciones_pago_usuario_estado_idx
  on public.transacciones_pago (id_usuario, estado, creado_en desc);

create table if not exists public.series_comprobante (
  id bigint generated by default as identity primary key,
  ruc_emisor varchar(11) not null,
  tipo_comprobante varchar(7) not null check (tipo_comprobante in ('BOLETA', 'FACTURA')),
  serie varchar(4) not null,
  siguiente_numero bigint not null default 1 check (siguiente_numero > 0),
  actualizado_en timestamptz not null default now(),
  unique (ruc_emisor, tipo_comprobante, serie)
);

create table if not exists public.comprobantes_electronicos (
  id bigint generated by default as identity primary key,
  id_usuario bigint not null references public.usuarios(id),
  id_transaccion bigint not null unique references public.transacciones_pago(id),
  tipo_comprobante varchar(7) not null check (tipo_comprobante in ('BOLETA', 'FACTURA')),
  serie varchar(4) not null,
  numero bigint not null check (numero > 0),
  ambiente_sunat varchar(10) not null default 'beta' check (ambiente_sunat in ('beta', 'production')),
  estado_sunat varchar(16) not null default 'generando'
    check (estado_sunat in ('generando', 'enviado', 'procesando', 'aceptado', 'observado', 'rechazado', 'error')),
  ruc_emisor varchar(11) not null,
  razon_social_emisor text not null,
  tipo_documento_cliente varchar(3) not null,
  numero_documento_cliente varchar(15) not null,
  nombre_cliente text not null,
  direccion_cliente text,
  correo_cliente text not null,
  moneda varchar(3) not null default 'PEN',
  subtotal numeric(12, 2) not null,
  igv numeric(12, 2) not null,
  total numeric(12, 2) not null,
  ruta_xml text,
  ruta_pdf text,
  ruta_cdr text,
  ticket_sunat text,
  codigo_respuesta_sunat text,
  descripcion_respuesta_sunat text,
  resumen_hash text,
  correo_enviado_en timestamptz,
  enviado_sunat_en timestamptz,
  aceptado_sunat_en timestamptz,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  unique (ruc_emisor, tipo_comprobante, serie, numero)
);

create index if not exists comprobantes_usuario_idx
  on public.comprobantes_electronicos (id_usuario, creado_en desc);

create table if not exists public.eventos_webhook_culqi (
  id bigint generated by default as identity primary key,
  event_id text not null unique,
  event_type text,
  culqi_object_id text,
  payload_hash text not null,
  procesado boolean not null default false,
  mensaje_error text,
  recibido_en timestamptz not null default now(),
  procesado_en timestamptz
);

